"""Walk-forward runner. Models, score thresholds and drift flags only use the past."""
from __future__ import annotations
import time
import tracemalloc
from pathlib import Path
import numpy as np
import pandas as pd
from scipy.stats import ks_2samp, wilcoxon
from .data import load_catalog
from .detectors import DETECTOR_NAMES, make_detector
from .metrics import compute

def drift_flag(history: np.ndarray) -> bool:
    if len(history) < 80: return False
    return bool(ks_2samp(history[-40:-20], history[-20:]).pvalue < .05)

def run(output: str = "artifacts", datasets: int = 12, cadences: list[int] | None = None) -> pd.DataFrame:
    """Run rolling origins without making future rows visible to fit or thresholding."""
    cadences = cadences or [7, 14, 28]; rows=[]
    for data in load_catalog(datasets):
      v=data.frame.value.to_numpy(); y=data.frame.label.to_numpy(); initial=220; step=40
      for name in DETECTOR_NAMES:
       for regime, cadence in [("static", 999999), *[("retrained", c) for c in cadences]]:
        model=make_detector(name); model.fit(v[:initial]); last=initial
        for start in range(initial, len(v)-step+1, step):
          past=v[:start]
          # Streams are hourly; configured cadence is in calendar days.
          if regime=="retrained" and start-last >= cadence * 24:
              model.retrain(past)
              last=start
          tracemalloc.start(); tic=time.perf_counter(); score=model.score(v[start:start+step]); runtime=time.perf_counter()-tic; _,peak=tracemalloc.get_traced_memory(); tracemalloc.stop()
          m=compute(y[start:start+step],score,model.score(past[-min(len(past),200):]))
          rows.append({"dataset":data.name,"detector":name,"regime":regime,"cadence":cadence,"window_start":start,"post_drift":drift_flag(past),"runtime_s":runtime,"memory_mb":peak/1e6,**m})
    df=pd.DataFrame(rows); out=Path(output); out.mkdir(parents=True,exist_ok=True); df.to_csv(out/"results.csv",index=False)
    summary=df.groupby(["detector","regime","cadence"],dropna=False).agg(pr_auc=("pr_auc","mean"),f1=("f1","mean"),runtime_s=("runtime_s","mean"),memory_mb=("memory_mb","mean")).reset_index(); summary.to_csv(out/"leaderboard.csv",index=False)
    _write_findings(df,out); return df

def _write_findings(df: pd.DataFrame, out: Path) -> None:
    static=df[df.regime=="static"].groupby("dataset").pr_auc.mean(); retr=df[(df.regime=="retrained") & (df.cadence==7)].groupby("dataset").pr_auc.mean(); common=static.index.intersection(retr.index)
    stat,p=wilcoxon(retr[common],static[common],zero_method="zsplit") if len(common)>1 else (float("nan"),float("nan"))
    best=df.groupby(["detector","regime","cadence"]).pr_auc.mean().sort_values(ascending=False).head(1)
    text="# Results\n\nGenerated by `python -m anomaly_bench run`.\n\n"
    text+=f"Best mean window PR-AUC: **{best.iloc[0]:.3f}** ({best.index[0]}).\n\n"
    text+=f"Cadence-7 vs static paired Wilcoxon across {len(common)} datasets: p={p:.4g}; statistic={stat:.3g}. "
    text+="This small synthetic fallback benchmark is a smoke-test result, not evidence about public datasets.\n"
    (out/"RESULTS.generated.md").write_text(text,encoding="utf-8")
